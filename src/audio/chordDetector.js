/**
 * Polyphonic Chord Detector using 12-bin Chromagram / Pitch Class Profile (PCP)
 * and Guitar-Calibrated Harmonic Weighting.
 */
import { NOTE_NAMES, CHORD_DEFINITIONS } from './chordDictionary.js';

export class ChordDetector {
  constructor(sampleRate = 44100, fftSize = 4096) {
    this.sampleRate = sampleRate;
    this.fftSize = fftSize;
    this.chromagram = new Float32Array(12);
    this.smoothedChromagram = new Float32Array(12);
    this.smoothingFactor = 0.30;
  }

  setSampleRate(rate) {
    this.sampleRate = rate;
  }

  /**
   * Generates a 12-dimensional Chromagram from the FFT frequency spectrum.
   * Calibrated for acoustic and electric guitars (E2 82Hz to E5 660Hz + harmonics).
   */
  computeChromagram(frequencyData) {
    this.chromagram.fill(0);
    const numBins = frequencyData.length;
    const binWidth = (this.sampleRate / 2) / numBins;

    // Guitar musical range: ~80Hz to ~2200Hz
    const minBin = Math.max(1, Math.floor(80 / binWidth));
    const maxBin = Math.min(numBins - 1, Math.floor(2200 / binWidth));

    for (let bin = minBin; bin <= maxBin; bin++) {
      const freq = bin * binWidth;
      
      // Semitone index relative to A4 (440Hz, pitch class 9)
      const midiFraction = 12 * (Math.log2(freq / 440)) + 69;
      const pitchClass = (Math.round(midiFraction) % 12 + 12) % 12;

      let magnitude = 0;
      if (frequencyData instanceof Uint8Array) {
        magnitude = frequencyData[bin] / 255;
      } else {
        const db = frequencyData[bin];
        magnitude = db > -80 ? Math.pow(10, db / 20) : 0;
      }

      // Guitar Equalization: Emphasize fundamental guitar register (100Hz - 900Hz)
      const guitarFreqWeight = freq < 150 ? 0.85 : freq < 900 ? 1.25 : 0.8;
      this.chromagram[pitchClass] += magnitude * guitarFreqWeight;
    }

    // Exponential smoothing
    let maxVal = 0;
    for (let i = 0; i < 12; i++) {
      this.smoothedChromagram[i] = (1 - this.smoothingFactor) * this.chromagram[i] + this.smoothingFactor * this.smoothedChromagram[i];
      if (this.smoothedChromagram[i] > maxVal) {
        maxVal = this.smoothedChromagram[i];
      }
    }

    // Normalize to 0..1
    if (maxVal > 0.0001) {
      for (let i = 0; i < 12; i++) {
        this.smoothedChromagram[i] /= maxVal;
      }
    }

    return this.smoothedChromagram;
  }

  /**
   * Compares the current chromagram with known chord definitions with strict harmonic correlation.
   * Rejects single-string overtone triads when a monophonic pitch is detected.
   */
  matchChord(chromagram, minConfidence = 0.58, detectedPitch = null) {
    let bestChord = null;
    let highestScore = -1;

    let totalEnergy = 0;
    for (let i = 0; i < 12; i++) {
      totalEnergy += chromagram[i];
    }
    // Require sufficient acoustic energy (not noise or faint silence)
    if (totalEnergy < 0.9) {
      return null;
    }

    // Require at least 2 distinct pitch classes with significant energy (triads need 3, power chords need 2)
    let strongBinsCount = 0;
    for (let i = 0; i < 12; i++) {
      if (chromagram[i] >= 0.26) {
        strongBinsCount++;
      }
    }
    if (strongBinsCount < 2) {
      return null;
    }

    // Single-note harmonic rejection:
    // A vibrating single guitar string naturally produces the fundamental (root), 3rd harmonic (5th), and 5th harmonic (3rd).
    // If a clean monophonic pitch is detected with high confidence (> 0.82), we check if the chromagram is only
    // reflecting that single string's harmonic overtone series rather than a true polyphonic chord.
    if (detectedPitch && detectedPitch.confidence > 0.82) {
      const rootPc = detectedPitch.noteIndex;
      const harmonicFifth = (rootPc + 7) % 12;
      const harmonicThird = (rootPc + 4) % 12;

      // Count energy of independent notes not generated by this string's overtone series
      let nonHarmonicEnergy = 0;
      let nonHarmonicStrongBins = 0;
      for (let i = 0; i < 12; i++) {
        if (i !== rootPc && i !== harmonicFifth && i !== harmonicThird) {
          if (chromagram[i] > 0.28) {
            nonHarmonicEnergy += chromagram[i];
            nonHarmonicStrongBins++;
          }
        }
      }

      // If there are no independent non-harmonic tones, this is definitively a single note, NOT a chord!
      if (nonHarmonicStrongBins === 0 || nonHarmonicEnergy < 0.35) {
        return null;
      }
    }

    for (const [chordKey, chordData] of Object.entries(CHORD_DEFINITIONS)) {
      const activeClasses = chordData.pitchClasses;
      let inChordEnergy = 0;
      let outChordEnergy = 0;
      let presentCount = 0;

      const rootIndex = NOTE_NAMES.indexOf(chordData.root);
      const rootStrength = rootIndex >= 0 ? chromagram[rootIndex] : 0;

      // Root must be audible
      if (rootStrength < 0.25) {
        continue;
      }

      for (let i = 0; i < 12; i++) {
        if (activeClasses.includes(i)) {
          inChordEnergy += chromagram[i];
          if (chromagram[i] > 0.25) {
            presentCount++;
          }
        } else {
          outChordEnergy += chromagram[i];
        }
      }

      const expectedCount = activeClasses.length;
      const avgInChord = inChordEnergy / expectedCount;
      const avgOutChord = outChordEnergy / (12 - expectedCount);

      // Strict energy ratio (in-chord must dominate out-of-chord noise)
      const energyRatio = inChordEnergy / (inChordEnergy + outChordEnergy + 0.001);
      if (energyRatio < 0.55) {
        continue;
      }

      // Must have at least all chord notes (or all but 1 for 7th chords)
      const minRequiredNotes = expectedCount > 3 ? expectedCount - 1 : expectedCount;
      if (presentCount < minRequiredNotes) {
        continue;
      }

      // Penalty for high intruder notes
      let maxIntruderEnergy = 0;
      for (let i = 0; i < 12; i++) {
        if (!activeClasses.includes(i) && chromagram[i] > maxIntruderEnergy) {
          maxIntruderEnergy = chromagram[i];
        }
      }

      let score = (avgInChord * 1.6) - (avgOutChord * 1.2) - (maxIntruderEnergy * 0.5) + (rootStrength * 0.4);

      if (presentCount === expectedCount) {
        score += 0.35; // All notes present bonus
      }

      if (score > highestScore) {
        highestScore = score;
        const confidence = Math.min(0.99, Math.max(0, (score - 0.2) / 1.15));
        bestChord = {
          ...chordData,
          score,
          confidence,
          chromagramEnergy: inChordEnergy
        };
      }
    }

    if (bestChord && bestChord.confidence >= minConfidence) {
      return bestChord;
    }

    return null;
  }

  detectChord(frequencyData, minConfidence = 0.58, detectedPitch = null) {
    const chroma = this.computeChromagram(frequencyData);
    const match = this.matchChord(chroma, minConfidence, detectedPitch);
    return {
      chord: match,
      chromagram: Array.from(chroma)
    };
  }
}
